#!/bin/bash
# Compiles gatewayd (daemon) and GW Switch.app (menu-bar app).
# Zero external dependencies — uses the Swift compiler from Xcode Command Line Tools.
set -euo pipefail

cd "$(dirname "$0")"
BUILD="dist/build"
APP="$BUILD/GWSwitch.app"
rm -rf "$BUILD"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources" "$BUILD/libexec"
# Keep Spotlight/LaunchServices from indexing this build artifact as a second
# "GW Switch" app alongside the real /Applications install.
touch "$BUILD/.metadata_never_index"

# Apple Silicon (arm64) only.
compile() {
  xcrun swiftc -O -target arm64-apple-macos11 "$1" -o "$2"
}

echo "Compiling gatewayd (daemon)…"
compile daemon/gatewayd.swift "$BUILD/libexec/gatewayd"

echo "Compiling GW Switch (app)…"
compile app/GatewayTray.swift "$APP/Contents/MacOS/GWSwitch"

# App icon (generated by assets/make-icon.swift).
if [[ -f assets/AppIcon.icns ]]; then
  cp assets/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"
fi

cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>              <string>GW Switch</string>
    <key>CFBundleDisplayName</key>       <string>GW Switch</string>
    <key>CFBundleIdentifier</key>        <string>com.gatewaytray</string>
    <key>CFBundleVersion</key>           <string>1.0.4</string>
    <key>CFBundleShortVersionString</key><string>1.0.4</string>
    <key>CFBundlePackageType</key>       <string>APPL</string>
    <key>CFBundleExecutable</key>        <string>GWSwitch</string>
    <key>CFBundleIconFile</key>          <string>AppIcon</string>
    <key>LSMinimumSystemVersion</key>    <string>11.0</string>
    <key>LSUIElement</key>               <true/>
    <key>LSMultipleInstancesProhibited</key><true/>
</dict>
</plist>
PLIST

# Ad-hoc code signatures (no Developer ID; sufficient for local/internal use).
codesign --force --sign - "$BUILD/libexec/gatewayd" 2>/dev/null || true
codesign --force --deep --sign - "$APP" 2>/dev/null || true

echo "Built:"
echo "  $APP"
echo "  $BUILD/libexec/gatewayd"
echo
echo "Run 'packaging/build-pkg.sh' to produce the installer .pkg."
